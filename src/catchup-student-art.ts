export function prepareCatchupStudent(scene: Phaser.Scene) {
  const raw = scene.textures
    .get("raw-catchup-student")
    .getSourceImage() as HTMLImageElement;
  const canvas = document.createElement("canvas");
  canvas.width = raw.width;
  canvas.height = raw.height;
  const ctx = canvas.getContext("2d")!;
  ctx.beginPath();
  for (const outline of CATCHUP_OUTLINES) {
    ctx.moveTo(outline[0][0], outline[0][1]);
    for (const [x, y] of outline.slice(1)) ctx.lineTo(x, y);
    ctx.closePath();
  }
  ctx.clip();
  ctx.drawImage(raw, 0, 0);
  const atlas = scene.textures.addCanvas("catchup-student", canvas)!;
  CATCHUP_FRAMES.forEach(([x, y, w, h], n) => atlas.add(n, 0, x, y, w, h));
  atlas.setFilter(Phaser.Textures.FilterMode.NEAREST);
  scene.textures.remove("raw-catchup-student");
}
export function preloadCatchupStudent(scene: Phaser.Scene) {
  scene.load.image("raw-catchup-student", CATCHUP_STUDENT_DATA);
}
