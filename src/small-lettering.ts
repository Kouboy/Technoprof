const clean = (s: string) =>
  s
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toUpperCase()
    .replaceAll("’", "'");
export function smallWidth(s: string) {
  return (
    [...clean(s)].reduce(
      (n, c) => n + (rows[c] ?? rows["?"]).split("/")[0].length + 1,
      0,
    ) - 1
  );
}
export function smallPrint(
  g: {
    fillStyle: (c: number, a?: number) => unknown;
    fillRect: (x: number, y: number, w: number, h: number) => unknown;
  },
  x: number,
  y: number,
  s: string,
  c = 0x24333b,
) {
  g.fillStyle(c);
  let dx = Math.round(x);
  for (const ch of clean(s)) {
    const glyph = (rows[ch] ?? rows["?"]).split("/");
    glyph.forEach((r, j) =>
      [...r].forEach((v, i) => {
        if (v === "1") g.fillRect(dx + i, Math.round(y) + j, 1, 1);
      }),
    );
    dx += glyph[0].length + 1;
  }
}
