export function preloadCatchupAttacks(scene: Phaser.Scene) {
  scene.load.image("raw-catchup-attacks", CATCHUP_ATTACK_DATA);
}
export function prepareCatchupAttacks(scene: Phaser.Scene) {
  const raw = scene.textures
    .get("raw-catchup-attacks")
    .getSourceImage() as HTMLImageElement;
  const canvas = document.createElement("canvas");
  canvas.width = 435;
  canvas.height = 615 * CATCHUP_ATTACK_FRAMES.length;
  const ctx = canvas.getContext("2d")!;
  CATCHUP_ATTACK_FRAMES.forEach(([x, y], n) => {
    const outline = CATCHUP_ATTACK_OUTLINES[n];
    ctx.save();
    ctx.translate(-x, n * 615 - y);
    ctx.beginPath();
    ctx.moveTo(...(outline[0] as [number, number]));
    for (const [x, y] of outline.slice(1)) ctx.lineTo(x, y);
    ctx.closePath();
    ctx.clip();
    ctx.drawImage(raw, 0, 0);
    ctx.restore();
  });
  const atlas = scene.textures.addCanvas("catchup-attacks", canvas)!;
  CATCHUP_ATTACK_FRAMES.forEach(([, , w, h], n) =>
    atlas.add(n, 0, 0, n * 615, w, h),
  );
  atlas.setFilter(Phaser.Textures.FilterMode.NEAREST);
  scene.textures.remove("raw-catchup-attacks");
}
