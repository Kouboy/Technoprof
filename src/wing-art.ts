export class WingArt {
  background: Phaser.GameObjects.Image;
  student: Phaser.GameObjects.Image;
  constructor(scene: Phaser.Scene) {
    const bg = scene.textures.get("wing-34"),
      source = bg.getSourceImage() as HTMLImageElement;
    bg.add("floor", 0, 0, 0, source.width, Math.round(source.height * 0.75));
    bg.setFilter(Phaser.Textures.FilterMode.NEAREST);
    this.background = scene.add
      .image(7, 7, "wing-34", "floor")
      .setOrigin(0)
      .setDisplaySize(306, 168)
      .setDepth(1);
    const raw = scene.textures
      .get("raw-student-34")
      .getSourceImage() as HTMLImageElement;
    const canvas = document.createElement("canvas");
    canvas.width = raw.width;
    canvas.height = raw.height;
    const ctx = canvas.getContext("2d")!;
    ctx.beginPath();
    for (const outline of STUDENT_OUTLINES) {
      ctx.moveTo(...(outline[0] as [number, number]));
      for (const [x, y] of outline.slice(1)) ctx.lineTo(x, y);
      ctx.closePath();
    }
    ctx.clip();
    ctx.drawImage(raw, 0, 0);
    const atlas = scene.textures.addCanvas("student-34", canvas)!;
    STUDENT_FRAMES.forEach(([x, y, w, h], i) => atlas.add(i, 0, x, y, w, h));
    atlas.setFilter(Phaser.Textures.FilterMode.NEAREST);
    this.student = scene.add.image(0, 0, "student-34", 0).setDepth(2);
    this.hide();
  }
  static preload(scene: Phaser.Scene) {
    scene.load.image("wing-34", WING_DATA.wing);
    scene.load.image("raw-student-34", WING_DATA.student);
  }
  hide() {
    this.background.setVisible(false);
    this.student.setVisible(false);
  }
  pose(frame: number, x: number, facing: number, alpha = 1) {
    const [left, top, w, h, anchor] = STUDENT_FRAMES[frame];
    this.student
      .setTexture("student-34", frame)
      .setOrigin((anchor - left) / w, (800 - top) / h)
      .setPosition(x, 159)
      .setScale(0.11 * facing, 0.11)
      .setAlpha(alpha)
      .setVisible(true);
  }
}
