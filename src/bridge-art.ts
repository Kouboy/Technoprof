export class BridgeArt {
  background: Phaser.GameObjects.Image;
  guard: Phaser.GameObjects.Image;
  constructor(scene: Phaser.Scene) {
    const bg = scene.textures.get("bridge-33"),
      source = bg.getSourceImage() as HTMLImageElement;
    bg.add("floor", 0, 0, 0, source.width, Math.round(source.height * 0.75));
    bg.setFilter(Phaser.Textures.FilterMode.NEAREST);
    this.background = scene.add
      .image(7, 7, "bridge-33", "floor")
      .setOrigin(0)
      .setDisplaySize(306, 168)
      .setDepth(1);
    const raw = scene.textures
      .get("raw-guard-33")
      .getSourceImage() as HTMLImageElement;
    const canvas = document.createElement("canvas");
    canvas.width = raw.width;
    canvas.height = raw.height;
    const ctx = canvas.getContext("2d")!;
    ctx.beginPath();
    for (const outline of GUARD_OUTLINES) {
      ctx.moveTo(outline[0][0], outline[0][1]);
      for (const [x, y] of outline.slice(1)) ctx.lineTo(x, y);
      ctx.closePath();
    }
    ctx.clip();
    ctx.drawImage(raw, 0, 0);
    const atlas = scene.textures.addCanvas("guard-33", canvas)!;
    GUARD_FRAMES.forEach(([x, y, w, h], i) => atlas.add(i, 0, x, y, w, h));
    atlas.setFilter(Phaser.Textures.FilterMode.NEAREST);
    this.guard = scene.add.image(0, 0, "guard-33", 0).setDepth(2);
    this.hide();
  }
  static preload(scene: Phaser.Scene) {
    scene.load.image("bridge-33", BRIDGE_DATA.bridge);
    scene.load.image("raw-guard-33", BRIDGE_DATA.guard);
  }
  hide() {
    this.background.setVisible(false);
    this.guard.setVisible(false);
  }
  pose(frame: number, x: number, facing: number, alpha = 1) {
    const [left, top, w, h, anchor] = GUARD_FRAMES[frame];
    this.guard
      .setTexture("guard-33", frame)
      .setOrigin((anchor - left) / w, (770 - top) / h)
      .setPosition(x, 159)
      .setScale(0.14 * facing, 0.14)
      .setAlpha(alpha)
      .setVisible(true);
  }
}
