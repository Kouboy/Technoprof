// Preserve generated originals; only embed their bytes for native offline exports.
const fs = require('node:fs'), path = require('node:path');
const root = path.resolve(__dirname, '..');
const art = path.join(root, 'art/title-2026-10-23');
const sources = { TITLE_DATA: 'concept-v8-wear.png', FAILURE_DATA: 'failure-atlas-v3.png' };
const lines = ['// Generated by node tools/build-interface-art.cjs. Do not edit image bytes here.'];
for (const [name, file] of Object.entries(sources))
  lines.push(`export const ${name} = ${JSON.stringify('data:image/png;base64,' + fs.readFileSync(path.join(art, file)).toString('base64'))};`);
fs.writeFileSync(path.join(root, 'src/interface-data.ts'), lines.join('\n') + '\n');
console.log('Embedded approved title and failure atlas for offline delivery.');
